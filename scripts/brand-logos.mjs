// Builds components/marketing/brand-logos.ts: the payment brand marks on the
// front page's ways-to-pay strip, as inline SVG data (no runtime package).
//
//   node scripts/brand-logos.mjs [simple-icons dir] [cryptocurrency-icons dir]
//
// Sources (both CC0): simple-icons@16.37.0 for payment brands and NEAR,
// cryptocurrency-icons@0.18.1 for coins. Brands with no openly licensed
// mark (UPI, M-Pesa, MTN MoMo, USSD, Faster Payments) are drawn as wordmark
// tiles by the component instead of imitating their logos.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [siDir, ccDir] = process.argv.slice(2);
const SI = "https://cdn.jsdelivr.net/npm/simple-icons@16.37.0";
const CC = "https://cdn.jsdelivr.net/npm/cryptocurrency-icons@0.18.1";
const read = async (dir, rel, url) => (dir ? readFileSync(join(dir, rel), "utf8") : (await fetch(url)).text());

// id → [source, file, colour for single-colour marks]
const brands = {
  visa: ["si", "visa", "#1A1F71"],
  mastercard: ["si", "mastercard", "#EB001B"],
  amex: ["si", "americanexpress", "#2E77BC"],
  applepay: ["si", "applepay", "#000000"],
  googlepay: ["si", "googlepay", "#4285F4"],
  paypal: ["si", "paypal", "#002991"],
  venmo: ["si", "venmo", "#008CFF"],
  picpay: ["si", "picpay", "#21C25E"],
  pix: ["si", "pix", "#32BCAD"],
  sepa: ["si", "sepa", "#2350A9"],
  near: ["si", "near", "#000000"],
  optimism: ["si", "optimism", "#FF0420"],
  usdc: ["cc", "usdc"],
  usdt: ["cc", "usdt"],
  btc: ["cc", "btc"],
  eth: ["cc", "eth"],
  sol: ["cc", "sol"],
  xlm: ["cc", "xlm"],
  matic: ["cc", "matic"],
  avax: ["cc", "avax"],
  trx: ["cc", "trx"],
  bnb: ["cc", "bnb"],
};

const out = {};
for (const [id, [source, file, color]] of Object.entries(brands)) {
  const svg =
    source === "si"
      ? await read(siDir, `icons/${file}.svg`, `${SI}/icons/${file}.svg`)
      : await read(ccDir, `svg/color/${file}.svg`, `${CC}/svg/color/${file}.svg`);
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  let body = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/<title>[\s\S]*?<\/title>/, "");
  if (source === "si") body = body.replace("<path ", `<path fill="${color}" `);
  out[id] = { viewBox, body: body.trim() };
}

writeFileSync(
  new URL("../components/marketing/brand-logos.ts", import.meta.url),
  `// Generated by scripts/brand-logos.mjs from simple-icons and cryptocurrency-icons (CC0). Do not edit.\n` +
    `export const brandLogos: Record<string, { viewBox: string; body: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(Object.keys(out).length, "logos");
