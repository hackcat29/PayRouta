// Builds components/gpu/globe-land.ts: which points of a Fibonacci sphere fall
// on land, as a base64 bitset. The homepage globe rebuilds the points from
// their index, so the shipped data is ~2 KB instead of a map.
//
//   node scripts/globe-land.mjs [path/to/land-110m.json]
//
// Source: Natural Earth via world-atlas (public domain).
import { readFileSync, writeFileSync } from "node:fs";

export const COUNT = 16000;
const src = process.argv[2];
const topo = src
  ? JSON.parse(readFileSync(src, "utf8"))
  : await (await fetch("https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json")).json();

// TopoJSON arcs are quantized and delta-encoded.
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});
const ring = (ids) =>
  ids.flatMap((id, i) => {
    const pts = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
    return i ? pts.slice(1) : pts;
  });
const polygons = topo.objects.land.geometries.flatMap((g) =>
  g.type === "Polygon" ? [g.arcs.map(ring)] : g.arcs.map((p) => p.map(ring)),
);
const inRing = (lon, lat, r) => {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i];
    const [xj, yj] = r[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const onLand = (lon, lat) => polygons.some(([outer, ...holes]) => inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h)));

// Same sequence as landPoints() in components/gpu/globe-scene.tsx.
const golden = Math.PI * (3 - Math.sqrt(5));
const bits = new Uint8Array(Math.ceil(COUNT / 8));
let land = 0;
for (let i = 0; i < COUNT; i++) {
  const y = 1 - (2 * (i + 0.5)) / COUNT;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((golden * i * 180) / Math.PI + 180) % 360) + 360) % 360 - 180;
  if (onLand(lon, lat)) {
    bits[i >> 3] |= 1 << (i & 7);
    land++;
  }
}
writeFileSync(
  new URL("../components/gpu/globe-land.ts", import.meta.url),
  `// Generated by scripts/globe-land.mjs from Natural Earth (public domain). Do not edit.\n` +
    `export const globeCount = ${COUNT};\nexport const globeLand = "${Buffer.from(bits).toString("base64")}";\n`,
);
console.log(`${land} land points of ${COUNT}`);
