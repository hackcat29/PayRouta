import { renderBaseTemplate, stripHtmlToText } from "./base";

export interface TransactionReceiptProps {
  intentId: string;
  amount: string;
  currency: string;
  recipientName?: string;
  merchantName?: string;
  method: string;
  provider: string;
  status: "succeeded" | "failed" | "routed" | "refunded";
  timestamp: string;
  txHashOrRef?: string;
  siteUrl?: string;
}

export function renderTransactionReceiptEmail(props: TransactionReceiptProps): {
  subject: string;
  html: string;
  text: string;
} {
  const {
    intentId,
    amount,
    currency,
    recipientName,
    merchantName = "PayRouta Merchant",
    method,
    provider,
    status,
    timestamp,
    txHashOrRef,
    siteUrl = process.env.SITE_URL || "https://payrouta.com",
  } = props;

  const isSuccess = status === "succeeded";
  const subject = isSuccess
    ? `Payment Receipt for ${currency} ${amount} — ${merchantName}`
    : `Payment Status Update: ${status.toUpperCase()} — ${merchantName}`;

  const statusColor = isSuccess
    ? "#10B981"
    : status === "routed"
      ? "#38BDF8"
      : "#EF4444";

  const bodyContent = `
    <p>Hi ${recipientName || "there"},</p>
    <p>
      This is a confirmation of your transaction processed through PayRouta for <strong>${merchantName}</strong>.
    </p>

    <div style="background: #0B0F19; border: 1px solid #1E293B; border-radius: 8px; padding: 20px; margin: 20px 0;">
      <table width="100%" cellpadding="6" cellspacing="0" style="font-size: 14px; color: #CBD5E1;">
        <tr>
          <td style="color: #94A3B8;">Amount:</td>
          <td align="right" style="color: #FFFFFF; font-weight: 700; font-size: 18px;">${currency} ${amount}</td>
        </tr>
        <tr>
          <td style="color: #94A3B8;">Status:</td>
          <td align="right" style="color: ${statusColor}; font-weight: 600; text-transform: capitalize;">${status}</td>
        </tr>
        <tr>
          <td style="color: #94A3B8;">Payment Rail / Method:</td>
          <td align="right" style="color: #FFFFFF;">${method}</td>
        </tr>
        <tr>
          <td style="color: #94A3B8;">Settlement Provider:</td>
          <td align="right" style="color: #FFFFFF;">${provider}</td>
        </tr>
        <tr>
          <td style="color: #94A3B8;">Transaction ID:</td>
          <td align="right" style="font-family: monospace; font-size: 12px; color: #38BDF8;">${intentId}</td>
        </tr>
        ${
          txHashOrRef
            ? `<tr>
                 <td style="color: #94A3B8;">Reference / Hash:</td>
                 <td align="right" style="font-family: monospace; font-size: 11px; color: #94A3B8;">${txHashOrRef}</td>
               </tr>`
            : ""
        }
        <tr>
          <td style="color: #94A3B8;">Date &amp; Time:</td>
          <td align="right" style="color: #CBD5E1; font-size: 13px;">${timestamp}</td>
        </tr>
      </table>
    </div>

    <p style="font-size: 13px; color: #94A3B8;">
      If you did not initiate this payment or have questions, please reach out to the merchant or contact PayRouta support.
    </p>
  `;

  const html = renderBaseTemplate({
    previewText: `Payment receipt: ${currency} ${amount} for ${merchantName}. Status: ${status}.`,
    headline: isSuccess ? "Payment Completed" : "Payment Notice",
    bodyContent,
    ctaText: "View Transaction Status",
    ctaUrl: `${siteUrl}/checkout/status/${intentId}`,
    footerNote: "This is a transactional receipt generated by PayRouta.",
  });

  return {
    subject,
    html,
    text: stripHtmlToText(html),
  };
}
